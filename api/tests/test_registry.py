"""The effect registry is the single source of truth for what we can render.

Three guarantees are tested here:
  1. `arsenal.md` is exactly what the registry renders (no hand edits).
  2. Every effect tool is in the registry, and every registry entry only
     names parameters its MCP tool really accepts.
  3. Every MCP tool is classified, so a new tool cannot slip in unnoticed.

The MCP server lives in a sibling package; it is read as text via `ast`,
never imported.
"""

import ast
from pathlib import Path

import pytest

from ai_video_editor import registry
from ai_video_editor.registry import (
    EFFECT_TOOLS,
    NON_EFFECT_TOOLS,
    NOT_RENDERABLE,
    REGISTRY,
    render_arsenal_md,
)

REPO_ROOT = Path(__file__).resolve().parents[2]
ARSENAL_PATH = REPO_ROOT / ".claude" / "skills" / "editing-expert" / "arsenal.md"
MCP_SERVER = REPO_ROOT / "mcp" / "src" / "ai_video_editor_mcp" / "server.py"


def _mcp_tool_params() -> dict[str, set[str]]:
    """Map every `@mcp.tool()` function in server.py to its parameter names."""
    tree = ast.parse(MCP_SERVER.read_text(encoding="utf-8"))
    return {
        node.name: {arg.arg for arg in node.args.args}
        for node in tree.body
        if isinstance(node, ast.FunctionDef)
        and any(ast.unparse(d) == "mcp.tool()" for d in node.decorator_list)
    }


def test_arsenal_md_matches_registry_byte_for_byte():
    assert ARSENAL_PATH.read_text(encoding="utf-8") == render_arsenal_md()


def test_arsenal_md_has_generated_header():
    text = render_arsenal_md()
    assert "GENERATED by registry.py" in text
    assert "GENERATED-PENDING" not in text


def test_not_renderable_kinds_listed_and_absent_from_registry():
    text = render_arsenal_md()
    assert "Not renderable yet" in text
    for kind in NOT_RENDERABLE:
        assert f"`{kind}`" in text
        assert kind not in REGISTRY


def test_every_registry_entry_is_keyed_by_its_own_kind():
    for kind, spec in REGISTRY.items():
        assert spec.kind == kind


def test_every_effect_tool_has_a_registry_entry():
    covered = {tool for spec in REGISTRY.values() for tool in (spec.mcp_tool, *spec.also_tools)}
    assert covered == EFFECT_TOOLS


def test_every_registry_entry_names_a_real_mcp_tool():
    tools = _mcp_tool_params()
    for spec in REGISTRY.values():
        for tool in (spec.mcp_tool, *spec.also_tools):
            assert tool in tools, f"{spec.kind}: {tool} is not an MCP tool"


def test_params_model_fields_are_parameters_of_the_mcp_tool():
    tools = _mcp_tool_params()
    for spec in REGISTRY.values():
        fields = set(spec.params_model.model_fields)
        assert fields <= tools[spec.mcp_tool], (
            f"{spec.kind}: {fields - tools[spec.mcp_tool]} not accepted by {spec.mcp_tool}"
        )


def test_every_mcp_tool_is_classified_exactly_once():
    assert not EFFECT_TOOLS & NON_EFFECT_TOOLS
    unclassified = set(_mcp_tool_params()) - EFFECT_TOOLS - NON_EFFECT_TOOLS
    assert not unclassified, f"add to registry or NON_EFFECT_TOOLS: {unclassified}"


def test_classified_tools_all_exist_in_the_mcp_server():
    stale = (EFFECT_TOOLS | NON_EFFECT_TOOLS) - set(_mcp_tool_params())
    assert not stale, f"registry names tools the MCP server lacks: {stale}"


def test_cli_write_rewrites_arsenal(tmp_path, monkeypatch):
    target = tmp_path / "arsenal.md"
    monkeypatch.setattr(registry, "ARSENAL_PATH", target)
    registry.main(["--write"])
    assert target.read_text(encoding="utf-8") == render_arsenal_md()


def test_cli_without_flag_prints_and_writes_nothing(tmp_path, monkeypatch, capsys):
    target = tmp_path / "arsenal.md"
    monkeypatch.setattr(registry, "ARSENAL_PATH", target)
    registry.main([])
    assert not target.exists()
    assert render_arsenal_md() in capsys.readouterr().out


@pytest.mark.parametrize("kind", ["zoom", "focus", "caption", "sfx", "music"])
def test_core_kinds_are_registered(kind):
    assert kind in REGISTRY
